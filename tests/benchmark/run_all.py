"""Run the full benchmark suite and write results to a markdown doc.

Usage:
    python -m tests.benchmark.run_all            # default mocked mode
    python -m tests.benchmark.run_all --real     # use real local LLM
    python -m tests.benchmark.run_all --no-bb   # skip live-API benches
"""

from __future__ import annotations

import argparse
import json
import os
import platform
import sys
import time
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[2]
RESULTS_PATH = PROJECT_ROOT / "tests" / "benchmark" / "BENCHMARK_RESULTS.md"

sys.path.insert(0, str(PROJECT_ROOT))

os.environ.setdefault("APP_ENV", "test")


def _host_summary() -> dict:
    return {
        "platform": platform.platform(),
        "python": platform.python_version(),
        "processor": platform.processor() or "unknown",
        "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
    }


def _format_table(rows: list[tuple[str, str, str, str]]) -> str:
    out = ["| Metric | Current | Target | Status |", "|---|---|---|---|"]
    for name, current, target, status in rows:
        out.append(f"| {name} | {current} | {target} | {status} |")
    return "\n".join(out)


def _render_markdown(results: dict, env_meta: dict, hosts: dict) -> str:
    """Turn the benchmark results dict into a markdown summary."""
    crit_metrics = []
    q = results["query"]
    crit_metrics.append(("Query: NDCG@5 (mean over synthetic queries)",
                         f"{q['summary']['ndcg@5']:.3f}", "≥ 0.500",
                         "✅" if q["summary"]["ndcg@5"] >= 0.5 else "❌"))
    crit_metrics.append(("Query: MRR (mean over synthetic queries)",
                         f"{q['summary']['mrr']:.3f}", "≥ 0.500",
                         "✅" if q["summary"]["mrr"] >= 0.5 else "❌"))
    crit_metrics.append(("Query: Precision@5 (mean)",
                         f"{q['summary']['p@5']:.3f}", "≥ 0.400",
                         "✅" if q["summary"]["p@5"] >= 0.4 else "❌"))
    crit_metrics.append(("Query: Recall@5 (mean)",
                         f"{q['summary']['recall@5']:.3f}", "≥ 0.500",
                         "✅" if q["summary"]["recall@5"] >= 0.5 else "❌"))

    s = results["summarize"]["summary"]
    crit_metrics.append(("Summarize: section completeness (all 7 non-empty)",
                         f"{s['section_completeness']:.2%}", "≥ 0.95",
                         "✅" if s["section_completeness"] >= 0.95 else "❌"))
    crit_metrics.append(("Summarize: ROUGE-L (overall vs abstract)",
                         f"{s['rouge_l_overall_vs_abstract']:.3f}", "≥ 0.250",
                         "✅" if s["rouge_l_overall_vs_abstract"] >= 0.25 else "❌"))
    crit_metrics.append(("Summarize: coverage judge mean (1-5)",
                         f"{s['coverage_judge_mean_1to5']:.2f}", "≥ 3.50",
                         "✅" if s["coverage_judge_mean_1to5"] >= 3.5 else "❌"))

    i = results["ideas"]["summary"]
    crit_metrics.append(("Ideas: count returned (mean)",
                         f"{i['ideas_per_paper_mean']:.1f}", "≥ 2.5",
                         "✅" if i["ideas_per_paper_mean"] >= 2.5 else "❌"))
    crit_metrics.append(("Ideas: plausibility judge mean (1-5)",
                         f"{i['plausibility_judge_mean_1to5']:.2f}", "≥ 3.00",
                         "✅" if i["plausibility_judge_mean_1to5"] >= 3.0 else "❌"))

    n = results["novelty"]["summary"]
    crit_metrics.append(("Novelty: accuracy vs ground truth",
                         f"{n['accuracy']:.2%}", "≥ 70%",
                         "✅" if n["accuracy"] >= 0.7 else "❌"))

    e = results["extraction"]["summary"]
    crit_metrics.append(("Extraction: schema coverage (8-field canonical)",
                         f"{e['schema_coverage']:.2%}", "≥ 0.80",
                         "✅" if e["schema_coverage"] >= 0.8 else "❌"))

    ts = results["tool_selection"]
    crit_metrics.append(("Tool selection: stub-router accuracy on synthetic-task set",
                         f"{ts['accuracy']:.2%} ({ts['n_tasks']} tasks)", "≥ 0.85",
                         "✅" if ts["accuracy"] >= 0.85 else "❌"))
    crit_metrics.append(("Tool count (was 9, target 3)",
                         str(ts["surface_new"]["tool_count"]), "≤ 3",
                         "✅" if ts["surface_new"]["tool_count"] <= 3 else "❌"))
    crit_metrics.append(("Tool arg count reduction (was 32, target ≤ 27)",
                         str(ts["surface_new"]["arg_count"]), "≤ 27",
                         "✅" if ts["surface_new"]["arg_count"] <= 27 else "❌"))

    body = []
    body.append("# ArXivum Benchmark Results")
    body.append("")
    body.append("Auto-generated by `python -m tests.benchmark.run_all`.")
    body.append("Mocked mode exercises the metric plumbing with deterministic")
    body.append("oracles; `--real` swaps in the local LLM as both summariser and judge.")
    body.append("Each row maps to a row in §6 of `docs/AI_RESEARCHER_CRITIQUE.md`.")
    body.append("")
    body.append(f"Python: {hosts['python']}  Platform: {hosts['platform']}")
    body.append(f"Embedder: stub (hash-based deterministic, {env_meta.get('embedder', 'stub')})")
    body.append(f"LLM judge: {env_meta.get('llm_judge', 'stub')}")
    body.append("")
    body.append("## Headline table")
    body.append("")
    body.append(_format_table(crit_metrics))
    body.append("")
    body.append("## Per-query retrieval (synthetic 4 queries)")
    body.append("")
    body.append("| Query | Top-K returned | Gold | NDCG@5 | P@5 |")
    body.append("|---|---|---|---|---|")
    for row in q["per_query"]:
        body.append(f"| {row['query']} | {', '.join(row['retrieved']) or '*none*'} | "
                    f"{', '.join(row['gold']) or '*none*'} | "
                    f"{row['ndcg@5']:.3f} | {row['p@5']:.3f} |")
    body.append("")
    body.append("## Novelty (synthetic labelled pairs)")
    body.append("")
    body.append("| Kind | Expected | Predicted | OK |")
    body.append("|---|---|---|---|")
    for row in results["novelty"]["per_pair"]:
        body.append(f"| {row['kind']} | {row['expected']} | {row['predicted']} | "
                    f"{'✅' if row['ok'] else '❌'} |")
    body.append("")
    body.append("## Extraction schema coverage (per paper, 8-field schema)")
    body.append("")
    body.append(f"  - Schema coverage rate: {e['schema_coverage']:.2%}")
    body.append(f"  - Papers tested: {e['n_papers']}")
    body.append("")
    body.append("| Field | Presence |")
    body.append("|---|---|")
    for fname, frac in e["per_field_presence"].items():
        body.append(f"| `{fname}` | {frac:.2%} |")
    body.append("")
    body.append("## How the numbers were produced")
    body.append("")
    body.append("```")
    body.append("python -m tests.benchmark.run_all                 # mocked mode (default)")
    body.append("python -m tests.benchmark.run_all --real          # real local LLM as judge")
    body.append("python -m tests.benchmark.run_all --no-bb        # skip live-API benches")
    body.append("```")
    body.append("")
    body.append("Mocked mode uses deterministic hash-based pseudo-embeddings for")
    body.append("retrieval and a stub LLM that returns canned 7-section summary")
    body.append("JSON. The stub embeds the oracle outputs so the metric plumbing is")
    body.append("exercised end-to-end; only the *quality* of the LLM is mocked.")
    body.append("Re-run with `--real` to substitute the local LLM as both the")
    body.append("summariser and the judge.")
    body.append("")
    return "\n".join(body)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--real", action="store_true", help="use real local LLM as judge")
    ap.add_argument("--no-bb", action="store_true", help="skip live-API benches")
    ap.add_argument("--out", default=str(RESULTS_PATH),
                    help="output markdown path")
    args = ap.parse_args(argv)

    from tests.benchmark.bench_runner import build_env
    from tests.benchmark.benchmarks import (
        bench_ideas,
        bench_novelty,
        bench_query,
        bench_summarize,
        bench_extraction,
        bench_latency,
        bench_validation,
    )
    from tests.benchmark.bench_tool_selection import bench_tool_selection

    use_real_llm = args.real

    env_meta = {"embedder": "stub", "llm_judge": "stub"}
    stub_judge_llm = None
    if use_real_llm:
        from src.inference.llm import LocalLLM
        from src.config import get_settings
        s = get_settings()
        llm = LocalLLM(model_path=s.llm_model_path, n_ctx=s.llm_n_ctx,
                       n_threads=s.llm_n_threads, n_gpu_layers=s.llm_n_gpu_layers)
        env_meta["llm_judge"] = "LocalLLM"
        env_meta["embedder"] = "BGE-small"
        stub_judge_llm = llm

    print("Building benchmark environment...")
    env = build_env(stub_llm=stub_judge_llm)
    if not use_real_llm:
        from tests.benchmark.benchmarks import ContextStubLLM
        env.ctx.models.set_llm(ContextStubLLM())

    from src.mcp_server.server import create_mcp_server
    mcp_instance = create_mcp_server(env.ctx)

    print("Running benchmarks (mocked mode by default)...")
    t0 = time.perf_counter()
    results: dict = {}
    results["query"] = bench_query(env)
    print(f"  query done ({(time.perf_counter()-t0):.1f}s)")
    results["summarize"] = bench_summarize(env)
    print(f"  summarize done ({(time.perf_counter()-t0):.1f}s)")
    results["ideas"] = bench_ideas(env)
    print(f"  ideas done ({(time.perf_counter()-t0):.1f}s)")
    results["novelty"] = bench_novelty(env)
    print(f"  novelty done ({(time.perf_counter()-t0):.1f}s)")
    results["extraction"] = bench_extraction(env)
    print(f"  extraction done ({(time.perf_counter()-t0):.1f}s)")
    router_llm = env.ctx.models.llm if use_real_llm else None
    results["tool_selection"] = bench_tool_selection(
        mcp_instance=mcp_instance, llm=router_llm,
    )
    print(f"  tool_selection done ({(time.perf_counter()-t0):.1f}s)")

    if not args.no_bb:
        try:
            import urllib.request
            urllib.request.urlopen("http://localhost:8000/api/v1/health", timeout=2).close()
            print("Live API is up - running live-API benches...")
            results["validation"] = bench_validation()
            results["latency"] = bench_latency(env)
        except Exception as exc:
            print(f"Live API unavailable ({exc}); skipping network benches")
    else:
        print("--no-bb: skipping live-API benches")

    md = _render_markdown(results, env_meta=env_meta, hosts=_host_summary())
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text(md, encoding="utf-8")
    print(f"Wrote {args.out}")

    Path(args.out).with_suffix(".json").write_text(
        json.dumps(results, default=str, indent=2),
        encoding="utf-8",
    )
    print(f"Wrote {Path(args.out).with_suffix('.json')}")

    env.close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
